// ───────────────────────── number formats ─────────────────────────

type Restart = "NEVER" | "YEARLY" | "FINANCIAL_YEAR";
interface Sequence { type: string; pattern: string; padding: number; resetPolicy: Restart; isDefault: boolean; nextNumber: number; example: string }
const SEQ_LABEL: Record<string, string> = {
  MRN: "Patient MRN", OPD_VISIT: "OPD visit", ADMISSION: "Admission", INVOICE: "Invoice", RECEIPT: "Receipt", PRESCRIPTION: "Prescription",
  CREDIT_NOTE: "Credit note", REFUND: "Refund", PURCHASE: "Purchase", PURCHASE_RETURN: "Purchase return", PHARMACY_RECEIPT: "Pharmacy sale",
  STOCK_TRANSFER: "Stock transfer", DOCTOR_PAYOUT: "Doctor payout", LAB_ACCESSION: "Lab sample", RAD_ACCESSION: "Radiology study", CLAIM: "Insurance claim", EMPLOYEE: "Employee",
};
const RESTART_LABEL: Record<Restart, string> = { NEVER: "Never", YEARLY: "Every January", FINANCIAL_YEAR: "Every April (financial year)" };
/** Bills that carry GST: at most 16 characters, only letters, digits, - and / (checked again by the server). */
const GST_TYPES = ["INVOICE", "CREDIT_NOTE", "PHARMACY_RECEIPT"];
/** Financial year of a date, 1 April to 31 March: "2026-27". */
const financialYear = (d: Date) => { const start = d.getMonth() >= 3 ? d.getFullYear() : d.getFullYear() - 1; return `${start}-${String((start + 1) % 100).padStart(2, "0")}`; };

/** How human-readable numbers look. Changes apply to new records only; numbers already issued never change. */
export function NumberingCard() {
  const { me } = useMe();
  const qc = useQueryClient();
  const list = useQuery({ queryKey: ["number-sequences"], queryFn: () => api.get<Sequence[]>("/number-sequences") });
  const [edit, setEdit] = useState<Sequence | null>(null);
  const [startAt, setStartAt] = useState("");
  const save = useMutation({
    mutationFn: (s: Sequence) => {
      const n = startAt.trim();
      return api.put(`/number-sequences/${s.type}`, { pattern: s.pattern.trim(), padding: s.padding, resetPolicy: s.resetPolicy, ...(n && Number(n) > 0 ? { nextNumber: Number(n) } : {}) });
    },
    onSuccess: async () => { setEdit(null); setStartAt(""); await qc.invalidateQueries({ queryKey: ["number-sequences"] }); },
  });
  // Preview only: the real number is generated by the server inside the transaction that creates the record.
  const preview = (s: Sequence, seq: number) => s.pattern.replace("{FACILITY}", me.facility?.code ?? "FAC").replace("{YEAR}", String(new Date().getFullYear())).replace("{FY}", financialYear(new Date())).replace("{SEQ}", String(seq).padStart(s.padding, "0"));
  const longest = edit ? preview(edit, 10 ** edit.padding - 1) : "";
  const tooLong = !!edit && GST_TYPES.includes(edit.type) && longest.length > 16;
  return (
    <Card title="Number formats">
      <p className="mb-2 text-xs text-slate-500">
        Use {"{SEQ}"} (required), {"{YEAR}"} (calendar year), {"{FY}"} (financial year, like 2026-27) and {"{FACILITY}"}. A format that restarts every year needs {"{YEAR}"}; one that restarts every April needs {"{FY}"}.
        Changes apply to new records only; numbers already given out never change and are never given out again. To carry on from an old register, set the next number: it can only move forward.
      </p>
      {list.isLoading ? <Spinner /> : (
        <Table head={["Record", "Format", "Next number", "Restarts", ""]}>
          {list.data?.map((s) => edit?.type === s.type ? (
            <tr key={s.type}><Td>{SEQ_LABEL[s.type] ?? s.type}</Td>
              <Td>
                <Input aria-label="Pattern" value={edit.pattern} onChange={(e) => setEdit({ ...edit, pattern: e.target.value })} />
                <div className="mt-1 flex items-center gap-1 text-xs">Digits <Input aria-label="Digits" className="w-16" inputMode="numeric" value={String(edit.padding)} onChange={(e) => setEdit({ ...edit, padding: Number(e.target.value.replace(/\D/g, "")) || 1 })} /></div>
                {GST_TYPES.includes(edit.type) && <div className={tooLong ? "mt-1 text-xs text-red-700" : "mt-1 text-xs text-slate-500"}>A bill number can be at most 16 characters and use only letters, digits, - and /. This one can reach {longest.length}.</div>}
              </Td>
              <Td>
                <code className="text-xs">{preview(edit, Math.max(s.nextNumber, Number(startAt) || 0))}</code>
                <div className="mt-1 text-xs">Start from <Input aria-label="Next number" className="w-24" inputMode="numeric" placeholder={String(s.nextNumber)} value={startAt} onChange={(e) => setStartAt(e.target.value.replace(/\D/g, ""))} /></div>
              </Td>
              <Td><Select aria-label="Restarts" value={edit.resetPolicy} onChange={(e) => setEdit({ ...edit, resetPolicy: e.target.value as Restart })}>{(Object.keys(RESTART_LABEL) as Restart[]).map((k) => <option key={k} value={k}>{RESTART_LABEL[k]}</option>)}</Select></Td>
              <Td><div className="flex gap-1"><Button loading={save.isPending} disabled={tooLong} onClick={() => save.mutate(edit)}>Save</Button><Button variant="ghost" onClick={() => { setEdit(null); setStartAt(""); save.reset(); }}>Cancel</Button></div></Td></tr>
          ) : (
            <tr key={s.type}><Td>{SEQ_LABEL[s.type] ?? s.type}</Td><Td><code className="text-xs">{s.pattern}</code> <span className="text-xs text-slate-500">· {s.padding} digits</span>{!s.isDefault && <> <Badge tone="blue">custom</Badge></>}</Td>
              <Td><code className="text-xs">{s.example}</code></Td><Td>{RESTART_LABEL[s.resetPolicy]}</Td>
              <Td>{!edit && <Button variant="ghost" onClick={() => { setEdit(s); setStartAt(""); save.reset(); }}>Edit</Button>}</Td></tr>
          ))}
        </Table>
      )}
      <ErrorNote error={save.error} />
    </Card>
  );
}

// ───────────────────────── print footers ─────────────────────────

const FOOTERS = [["invoice", "Invoice"], ["receipt", "Receipt"], ["prescription", "Prescription"], ["dischargeSummary", "Discharge summary"], ["admissionForm", "Admission form"]] as const;

/** Footer line printed at the bottom of each document type (e.g. "Thank you. Goods once sold will not be taken back."). */
export function FooterCard({ value, saving, onSave }: { value: Record<string, string> | null; saving: boolean; onSave: (v: Record<string, string>) => void }) {
  const [f, setF] = useState<Record<string, string> | null>(null);
  const form = f ?? value ?? {};
  return (
    <Card title="Print footer">
      <form className="grid gap-2 sm:grid-cols-2" onSubmit={(e) => { e.preventDefault(); onSave(Object.fromEntries(Object.entries(form).filter(([, x]) => x && x.trim()).map(([k, x]) => [k, x.trim()]))); setF(null); }}>
        {FOOTERS.map(([k, label]) => <Field key={k} label={label} hint="Up to 400 characters"><Input value={form[k] ?? ""} maxLength={400} onChange={(e) => setF({ ...form, [k]: e.target.value })} /></Field>)}
        <div className="sm:col-span-2"><Button type="submit" loading={saving} disabled={f === null}>Save footer</Button></div>
      </form>
    </Card>
  );
}

// ───────────────────────── doctor schedules ─────────────────────────

interface Win { dayOfWeek: number; start: string; end: string; slotMinutes: number }
const DAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

/** Weekly sessions for a doctor. Appointments can only be booked inside these sessions; slot length sets the booking step. */
export function ScheduleEditor({ doctors }: { doctors: { id: string; displayName: string }[] }) {
  const qc = useQueryClient();
  const [doc, setDoc] = useState("");
  const [wins, setWins] = useState<Win[] | null>(null);
  const load = useQuery({ queryKey: ["schedule", doc], queryFn: async () => { const w = await api.get<Win[]>(`/practitioners/${doc}/schedule`); setWins(w); return w; }, enabled: !!doc });
  const save = useMutation({
    mutationFn: () => api.put(`/practitioners/${doc}/schedule`, { windows: wins }),
    onSuccess: async () => { await qc.invalidateQueries({ queryKey: ["schedule", doc] }); await qc.invalidateQueries({ queryKey: ["practitioners-admin"] }); await qc.invalidateQueries({ queryKey: ["practitioners"] }); },
  });
  const patch = (i: number, p: Partial<Win>) => setWins((wins ?? []).map((w, j) => (j === i ? { ...w, ...p } : w)));
  const weekdays = (d: number) => (wins ?? []).map((w, i) => ({ w, i })).filter((x) => x.w.dayOfWeek === d);
  const preset = () => setWins([1, 2, 3, 4, 5, 6].map((dayOfWeek) => ({ dayOfWeek, start: "09:00", end: "13:00", slotMinutes: 15 })));
  return (
    <Card title="Weekly schedule">
      <div className="space-y-3">
        <p className="text-xs text-slate-500">A doctor with no saved schedule can be booked at any time. Once you save one, only these sessions can be booked, and a schedule saved with no sessions means the doctor cannot be booked. Visits already booked are kept.</p>
        <Field label="Doctor"><Select value={doc} onChange={(e) => { setDoc(e.target.value); setWins(null); }}><option value="">Choose…</option>{doctors.map((d) => <option key={d.id} value={d.id}>{d.displayName}</option>)}</Select></Field>
        {doc && load.isLoading && <Spinner />}
        {doc && wins && (
          <div className="space-y-2">
            {DAYS.map((name, d) => (
              <div key={name} className="grid grid-cols-12 items-start gap-2 border-b border-slate-100 pb-2">
                <div className="col-span-12 pt-1.5 text-sm font-medium sm:col-span-2"><T>{name}</T></div>
                <div className="col-span-12 space-y-1 sm:col-span-10">
                  {weekdays(d).length === 0 && <span className="text-sm text-slate-400">No session</span>}
                  {weekdays(d).map(({ w, i }) => (
                    <div key={i} className="flex flex-wrap items-center gap-2">
                      <Input aria-label={`${name} start`} type="time" className="w-28" value={w.start} onChange={(e) => patch(i, { start: e.target.value })} />
                      <span className="text-slate-400">to</span>
                      <Input aria-label={`${name} end`} type="time" className="w-28" value={w.end} onChange={(e) => patch(i, { end: e.target.value })} />
                      <Select aria-label={`${name} slot length`} className="w-32" value={String(w.slotMinutes)} onChange={(e) => patch(i, { slotMinutes: Number(e.target.value) })}>{[5, 10, 15, 20, 30, 45, 60].map((m) => <option key={m} value={m}>{m} min slots</option>)}</Select>
                      <button className="text-slate-400 hover:text-red-700" aria-label={`Remove ${name} session`} onClick={() => setWins(wins.filter((_, j) => j !== i))}>✕</button>
                    </div>
                  ))}
                  <button className="text-xs text-brand-700 hover:underline" onClick={() => setWins([...wins, { dayOfWeek: d, start: "09:00", end: "13:00", slotMinutes: 15 }])}>+ add session</button>
                </div>
              </div>
            ))}
            <div className="flex flex-wrap items-center gap-2">
              <Button loading={save.isPending} onClick={() => save.mutate()}>Save schedule</Button>
              <Button variant="ghost" onClick={preset}>Mon–Sat mornings</Button>
              {save.isSuccess && <span className="text-sm text-green-700">Saved</span>}
            </div>
            <ErrorNote error={save.error} />
          </div>
        )}
      </div>
    </Card>
  );
}

// ───────────────────────── roles ─────────────────────────

interface Role { id: string; name: string; isSystem: boolean; permissions: string[] }
const GROUP = (p: string) => p.split("_")[0] ?? p;
const nice = (p: string) => p.toLowerCase().replace(/_/g, " ");

function PermissionGrid({ all, value, onChange, disabled }: { all: string[]; value: Set<string>; onChange: (s: Set<string>) => void; disabled?: boolean }) {
  const groups = [...new Set(all.map(GROUP))];
  const toggle = (p: string) => { const n = new Set(value); if (n.has(p)) n.delete(p); else n.add(p); onChange(n); };
  return (
    <div className="grid gap-3 sm:grid-cols-2">
      {groups.map((g) => (
        <fieldset key={g} className="rounded-md border border-slate-200 p-2">
          <legend className="px-1 text-xs font-semibold uppercase tracking-wide text-slate-500">{g.toLowerCase()}</legend>
          {all.filter((p) => GROUP(p) === g).map((p) => (
            <label key={p} className="flex items-center gap-2 py-0.5 text-sm"><input type="checkbox" disabled={disabled} checked={value.has(p)} onChange={() => toggle(p)} /> {nice(p)}</label>
          ))}
        </fieldset>
      ))}
    </div>
  );
}

function RoleEditor({ role, all, onClose }: { role: Role | null; all: string[]; onClose: () => void }) {
  const qc = useQueryClient();
  const [name, setName] = useState(role?.name ?? "");
  const [perms, setPerms] = useState(new Set(role?.permissions ?? []));
  const readOnly = role?.isSystem ?? false;
  const save = useMutation({
    mutationFn: () => (role ? api.put(`/roles/${role.id}/permissions`, { permissions: [...perms] }) : api.post("/roles", { name: name.trim(), permissions: [...perms] })),
    onSuccess: async () => { await qc.invalidateQueries({ queryKey: ["roles"] }); onClose(); },
  });
  return (
    <Modal title={role ? (readOnly ? `${role.name.toLowerCase()} (built-in role)` : `Edit role — ${role.name}`) : "New role"} onClose={onClose} wide>
      <div className="space-y-3">
        {!role && <Field label="Role name"><Input autoFocus value={name} onChange={(e) => setName(e.target.value)} /></Field>}
        {readOnly && <Notice>Built-in roles cannot be changed. Create a custom role to give different access.</Notice>}
        <PermissionGrid all={all} value={perms} onChange={setPerms} disabled={readOnly} />
        <ErrorNote error={save.error} />
        <div className="flex justify-end gap-2"><Button variant="ghost" onClick={onClose}>Close</Button>{!readOnly && <ConfirmButton variant="primary" label="Save role" confirmLabel="Yes, change access" disabled={perms.size === 0 || (!role && name.trim().length < 2)} loading={save.isPending} onConfirm={() => save.mutate()} />}</div>
      </div>
    </Modal>
  );
}

export function RolesCard() {
  const roles = useQuery({ queryKey: ["roles"], queryFn: () => api.get<Role[]>("/roles") });
  const perms = useQuery({ queryKey: ["permissions"], queryFn: () => api.get<string[]>("/permissions") });
  const [editing, setEditing] = useState<Role | "new" | null>(null);
  return (
    <Card title="Roles and access" actions={<Button variant="secondary" onClick={() => setEditing("new")}>New role</Button>}>
      {roles.isLoading ? <Spinner /> : (
        <ul className="divide-y divide-slate-100">
          {roles.data?.map((r) => (
            <li key={r.id} className="flex items-center justify-between py-2 text-sm">
              <span><span className="font-medium">{r.name.toLowerCase()}</span> {r.isSystem && <Badge tone="gray">built-in</Badge>} <span className="text-slate-500">· {r.permissions.length} permissions</span></span>
              <Button variant="ghost" onClick={() => setEditing(r)}>{r.isSystem ? "View" : "Edit"}</Button>
            </li>
          ))}
        </ul>
      )}
      {editing && perms.data && <RoleEditor role={editing === "new" ? null : editing} all={perms.data} onClose={() => setEditing(null)} />}
    </Card>
  );
}

// ───────────────────────── staff: roles and password reset ─────────────────────────

export function StaffAccess({ user, onClose }: { user: { id: string; fullName: string; username: string; roles: { id: string; name: string }[]; departments?: { id: string; name: string }[] }; onClose: () => void }) {
  const qc = useQueryClient();
  const departments = useQuery({ queryKey: ["departments"], queryFn: () => api.get<{ id: string; name: string }[]>("/departments") });
  const [pickedDepts, setPickedDepts] = useState(new Set((user.departments ?? []).map((d) => d.id)));
  const setDepartments = useMutation({ mutationFn: () => api.put(`/users/${user.id}/departments`, { departmentIds: [...pickedDepts] }), onSuccess: async () => { await qc.invalidateQueries({ queryKey: ["users"] }); onClose(); } });
  const toggleDept = (id: string) => { const n = new Set(pickedDepts); if (n.has(id)) n.delete(id); else n.add(id); setPickedDepts(n); };
  const roles = useQuery({ queryKey: ["roles"], queryFn: () => api.get<Role[]>("/roles") });
  const [picked, setPicked] = useState(new Set(user.roles.map((r) => r.id)));
  const [pw, setPw] = useState("");
  const [pw2, setPw2] = useState("");
  const [showPw, setShowPw] = useState(false);
  const setRoles = useMutation({ mutationFn: () => api.put(`/users/${user.id}/roles`, { roleIds: [...picked] }), onSuccess: async () => { await qc.invalidateQueries({ queryKey: ["users"] }); onClose(); } });
  const reset = useMutation({ mutationFn: () => api.post(`/users/${user.id}/reset-password`, { password: pw }), onSuccess: () => { setPw(""); setPw2(""); setShowPw(false); } });
  const pwOk = pw.length >= 10 && pw === pw2;
  const toggle = (id: string) => { const n = new Set(picked); if (n.has(id)) n.delete(id); else n.add(id); setPicked(n); };
  return (
    <Modal title={`${user.fullName} (${user.username})`} onClose={onClose}>
      <div className="space-y-4">
        <div>
          <div className="mb-1 text-sm font-medium text-slate-700">Roles</div>
          {roles.isLoading ? <Spinner /> : roles.data?.map((r) => <label key={r.id} className="flex items-center gap-2 py-0.5 text-sm"><input type="checkbox" checked={picked.has(r.id)} onChange={() => toggle(r.id)} /> {r.name.toLowerCase()}</label>)}
          <ErrorNote error={setRoles.error} />
          <div className="mt-2"><ConfirmButton variant="primary" label="Save roles" confirmLabel="Yes, change access" disabled={picked.size === 0} loading={setRoles.isPending} onConfirm={() => setRoles.mutate()} /></div>
        </div>
        <div className="border-t border-slate-100 pt-3">
          <div className="mb-1 text-sm font-medium text-slate-700">What this person can see</div>
          <p className="mb-1 text-xs text-slate-500">Tick the departments whose patients, visits and reports this person may see. Leave all unticked to show everything their role allows. A doctor always sees only their own patients.</p>
          {departments.isLoading ? <Spinner /> : departments.data?.map((d) => <label key={d.id} className="flex items-center gap-2 py-0.5 text-sm"><input type="checkbox" checked={pickedDepts.has(d.id)} onChange={() => toggleDept(d.id)} /> {d.name}</label>)}
          <ErrorNote error={setDepartments.error} />
          <div className="mt-2"><ConfirmButton variant="primary" label="Save departments" confirmLabel="Yes, change what they see" loading={setDepartments.isPending} onConfirm={() => setDepartments.mutate()} /></div>
        </div>
        <div className="border-t border-slate-100 pt-3">
          <Field label="Set a new password" hint="At least 10 characters with upper case, lower case and a digit. The person is signed out everywhere straight away."><Input type={showPw ? "text" : "password"} autoComplete="new-password" value={pw} onChange={(e) => { setPw(e.target.value); reset.reset(); }} /></Field>
          <Field label="Type it again" error={pw2.length > 0 && pw !== pw2 ? "The two passwords are different" : undefined}><Input type={showPw ? "text" : "password"} autoComplete="new-password" value={pw2} onChange={(e) => setPw2(e.target.value)} /></Field>
          <label className="mt-1 flex items-center gap-2 text-sm text-slate-600"><input type="checkbox" checked={showPw} onChange={(e) => setShowPw(e.target.checked)} /> Show the password</label>
          {reset.isSuccess && <p className="mt-1 text-sm text-green-700">Password changed. {user.fullName} is signed out everywhere and must sign in with the new password: tell them what it is.</p>}
          <ErrorNote error={reset.error} />
          <div className="mt-2"><ConfirmButton variant="primary" label="Reset password" confirmLabel="Yes, reset" disabled={!pwOk} loading={reset.isPending} onConfirm={() => reset.mutate()} /></div>
        </div>
      </div>
    </Modal>
  );
}
